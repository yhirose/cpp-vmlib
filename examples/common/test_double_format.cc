int g_failed = 0;

void check(const std::string& got, const char* want, const char* what, double v) {
  if (got == want) return;
  std::fprintf(stderr, "FAIL: %s of %.17g: want %s, got %s\n", what, v, want,
               got.c_str());
  ++g_failed;
}


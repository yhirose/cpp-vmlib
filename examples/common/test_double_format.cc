int main() {
  for (const Row& r : kRows) {
    check(format_double(r.v, kPython), r.py, "python", r.v);
    check(format_double(r.v, kRuby), r.rb, "ruby", r.v);
    check(format_double(r.v, kJs), r.js, "js", r.v);
    if (r.cs) check(format_double(r.v, kCSharp), r.cs, "csharp", r.v);
    check(format_double(r.v, kGo), r.go, "go", r.v);
    check(format_double(r.v, kCulebra), r.cu, "culebra", r.v);
    check(format_double(r.v, kGuile), r.gu, "guile", r.v);
  }
  for (const Row32& r : kRows32) {
    check(format_float32(r.v, kGo), r.go, "go float32", r.v);
    check(format_float32(r.v, kCSharp), r.cs, "csharp float32", r.v);
  }
  // console.log(-0) is "-0", String(-0) is "0" -- the one value the two
  // surfaces of JavaScript spell differently.
  check(format_double(-0.0, kJs), "0", "js String", -0.0);
  check(format_double(-0.0, kJsInspect), "-0", "js inspect", -0.0);
  check(format_double(0.0, kJsInspect), "0", "js inspect", 0.0);
  check(format_double(1e21, kJsInspect), "1e+21", "js inspect", 1e21);
  if (g_failed != 0) {
    std::fprintf(stderr, "%d failed\n", g_failed);
    return 1;
  }
  std::puts("ok");
  return 0;
}

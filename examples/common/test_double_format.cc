// double_format.h's styles against what the real languages print. Every
// expected string below was printed by the language itself (Python 3,
// Ruby 3.0, Node, .NET 8, Go, culebra 0.8.0, Guile 3.0, Lua 5.4) for the
// same double: both sides of each language's thresholds, -0.0, the extremes
// and the digit counts around Guile's and Lua's cutoffs. Nothing here is a
// value the languages differ on between versions; C#'s inf and nan are left
// out because .NET spells them by culture, and Lua's nan because the C
// library gives it a sign on one machine and not on another.
//
// No VM: the formatter is a pure function of the double, so this runs in
// milliseconds.

